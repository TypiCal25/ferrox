"""Generate radix-8 schedules for the parallel-polynomial NTT."""
from pathlib import Path
import sys
from check_parallel_ntt import q
rep51=sum(1<<(51*i) for i in range(5));rep64=sum(1<<(64*i) for i in range(4))
M26=rep51*((1<<26)-1);M32=rep64*((1<<32)-1)
lines=['// SPDX-License-Identifier: MIT','// GENERATED by scripts/math/gen_fused_ntt.py; do not edit.','pragma solidity ^0.8.25;']
def emit(s):lines.append(s)
def literal(v):return '0x'+format(v,'x')
def pair(a,b,root,bias,inv):
    mask=M32 if inv else M26;qi=4236238847 if inv else 8380415;shift=32 if inv else 26
    emit('                {')
    emit(f'                    let root := shr(224, mload(add(tb, shl(2, {root}))))')
    if inv:
        emit(f'                    let u := add(x{a}, x{b})')
        emit(f'                    let v := mul(sub(add(x{a}, {literal(bias*rep64)}), x{b}), root)')
    else:emit(f'                    let v := mul(x{b}, root)')
    emit(f'                    v := shr({shift}, add(v, mul(and(mul(and(v, {literal(mask)}), {qi}), {literal(mask)}), 8380417)))')
    if inv:emit(f'                    x{a} := u\n                    x{b} := v')
    else:emit(f'                    x{b} := sub(add(x{a}, {literal(bias*rep51)}), v)\n                    x{a} := add(x{a}, v)')
    emit('                }')
for inv in (False,True):
    name='fusedInverse4' if inv else 'fusedForward5'
    emit(f'function {name}(uint256[] memory a, uint256 tb) pure {{')
    emit('    assembly ("memory-safe") {\n        let ap := add(a, 32)')
    if not inv:
        groups=[(1,32,3,0),(8,4,3,3),(64,1,2,6)]
    else:groups=[(32,1,3,0),(4,8,3,3),(1,64,2,6)]
    for groupsN,stride,stages,startstage in groups:
        width=1<<stages;span=width*stride
        emit('        {')
        emit(f'        for {{ let g := 0 }} lt(g, {groupsN}) {{ g := add(g, 1) }} {{')
        emit(f'            let base := add(ap, mul(g, {span*32}))')
        emit(f'            for {{ let off := 0 }} lt(off, {stride*32}) {{ off := add(off, 32) }} {{')
        emit('                let p := add(base, off)')
        for i in range(width):emit(f'                let x{i} := mload(add(p, {i*stride*32}))')
        for level in range(stages):
            dist=1<<level if inv else width>>(level+1)
            for block in range(0,width,2*dist):
                if inv:
                    heapStart=256>>(startstage+level+1)
                    root=f'sub({2*heapStart-1}, add(mul(g, {width//(2*dist)}), {block//(2*dist)}))'
                else:
                    m=1<<(startstage+level)
                    root=f'add({m}, add(mul(g, {1<<level}), {block//(2*dist)}))'
                bias=((1<<(startstage+level))*q if inv else (2 if startstage+level<4 else 3 if startstage+level<7 else 4)*q)
                for j in range(dist):pair(block+j,block+j+dist,root,bias,inv)
        for i in range(width):emit(f'                mstore(add(p, {i*stride*32}), x{i})')
        emit('            }\n        }\n        }')
    emit('    }\n}')
text='\n'.join(lines)+'\n';p=Path('src/FusedParallelNTT.sol')
if '--check' in sys.argv:
    assert p.read_text()==text,'generated fused source differs'
    print('PASS: generated fused source matches')
else:p.write_text(text)
