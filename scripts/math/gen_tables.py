"""Generate exact Montgomery twiddles; run with --check to detect drift."""
from pathlib import Path
import sys
from check_parallel_ntt import zetas,q,R26,R32

def table(scale,negative=False):
    return ''.join(((z*scale*(-1 if negative else 1))%q).to_bytes(4,'big').hex() for z in zetas)
rep51=sum(1<<(51*i) for i in range(5));rep64=sum(1<<(64*i) for i in range(4))
text='// SPDX-License-Identifier: MIT\n// GENERATED by scripts/math/gen_tables.py; do not edit.\npragma solidity ^0.8.25;\n'
for name,value in [('REP51',rep51),('MASK26X5',rep51*((1<<26)-1)),('REP64',rep64),('MASK32X4',rep64*((1<<32)-1))]:
    text+=f'uint256 constant {name} = 0x{value:064x};\n'
text+=f'bytes constant FW26 = hex"{table(R26)}";\nbytes constant IV32 = hex"{table(R32,True)}";\n'
text+=f'uint256 constant SCALE32 = {pow(256,-1,q)*R32%q};\n'
p=Path('src/NTTTables.sol')
if '--check' in sys.argv:
    assert p.read_text()==text,'generated tables differ'
    print('PASS: generated tables match source')
else:p.write_text(text)
